#!/usr/bin/env python3
"""Convert text fonts (see fonts/pocket-sans.txt) into C arrays of 1bpp rows.

Usage: font2c.py OUT.c SYMBOL=FONT.txt [SYMBOL=FONT.txt ...]
Each font becomes `const uint8_t SYMBOL[224][8]`: one byte per row, bit 7 = leftmost pixel
(the Game Boy's 1bpp layout), index = code - 32 for codes 32-255. Code 127 isn't used and is left blank.
The arrays go in ROM bank 1, which is always mapped at 0x4000 (the game never switches ROM banks).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import tdpsave  # noqa: E402

FIRST, LAST = 32, 255
CODES = [c for c in range(FIRST, LAST + 1) if tdpsave.editable(c)]   # 223 codes, in file order
LABELS = {32: "space", 160: "nbsp", 173: "shy"}


def label(code):
    return LABELS.get(code) or tdpsave.char_of(code)


def parse(path, full=True):
    """Return 224 glyphs (index code - 32), each a list of 8 row bytes; code 127 is all zero.

    Glyphs are listed in code order, 32-126 then 128-255, each with its character as the label. With
    full=False a file may stop after 126 (the other codes are then None).
    """
    glyphs, lab, rows = [], None, []
    lines = Path(path).read_text(encoding="utf-8").splitlines()

    def flush():
        if lab is None:
            return
        if len(glyphs) >= len(CODES):
            raise SystemExit(f"{path}: too many glyphs (found {lab!r} after code 255)")
        want = label(CODES[len(glyphs)])
        if lab != want:
            raise SystemExit(f"{path}: expected glyph {want!r} but found {lab!r}")
        if len(rows) != 8:
            raise SystemExit(f"{path}: glyph {lab!r} has {len(rows)} rows, needs 8")
        glyphs.append(rows)

    for n, line in enumerate(lines, 1):
        if line.startswith("#") and lab is None or not line.strip():
            continue
        if line.startswith(": "):
            flush()
            lab, rows = line[2:], []
            continue
        if len(line) != 8 or set(line) - {"#", "."}:
            raise SystemExit(f"{path}:{n}: rows must be 8 characters of '#' and '.'")
        rows.append(int(line.replace("#", "1").replace(".", "0"), 2))
    flush()
    if len(glyphs) != len(CODES) and (full or len(glyphs) != 95):
        raise SystemExit(f"{path}: found {len(glyphs)} glyphs, needs {len(CODES)} (codes 32-126 and 128-255)")
    out = [None] * (LAST - FIRST + 1)
    for code, g in zip(CODES, glyphs):
        out[code - FIRST] = g
    out[tdpsave.UNUSED - FIRST] = [0] * 8
    return out


def c_array(symbol, src):
    glyphs = parse(src)
    # comment labels: spell out the characters that could end a comment or a line, and code the rest
    names = {32: "space", 42: "star", 47: "slash", 92: "backslash", 127: "unused"}
    lines = []
    for i, g in enumerate(glyphs):
        code = FIRST + i
        name = names.get(code) or (chr(code) if code < 127 else f"U+{ord(tdpsave.char_of(code)):04X}")
        lines.append("    {" + ", ".join(f"0x{b:02X}" for b in g) + "}" + f", /* {code} {name} */")
    return f"/* {Path(src).name} */\nconst uint8_t {symbol}[{len(glyphs)}][8] = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    if len(sys.argv) < 3 or any("=" not in a for a in sys.argv[2:]):
        raise SystemExit(__doc__)
    out, pairs = sys.argv[1], [a.split("=", 1) for a in sys.argv[2:]]
    text = "/* Generated by tools/font2c.py. Do not edit. */\n#pragma bank 1\n#include <stdint.h>\n\n"
    text += "\n".join(c_array(sym, src) for sym, src in pairs)
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text(text)


if __name__ == "__main__":
    main()
