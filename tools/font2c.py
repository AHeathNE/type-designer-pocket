#!/usr/bin/env python3
"""Convert text fonts (see fonts/pocket-sans.txt) into C arrays of 1bpp rows.

Usage: font2c.py OUT.c SYMBOL=FONT.txt [SYMBOL=FONT.txt ...]
Each font becomes `const uint8_t SYMBOL[95][8]`: one byte per row, bit 7 = leftmost pixel
(the Game Boy's 1bpp layout), codes 32-126.
"""
import sys
from pathlib import Path

FIRST, LAST = 32, 126


def parse(path):
    """Return a list of 95 glyphs (codes 32-126), each a list of 8 row bytes."""
    glyphs, label, rows = [], None, []
    lines = Path(path).read_text(encoding="utf-8").splitlines()

    def flush():
        if label is None:
            return
        code = FIRST + len(glyphs)
        want = "space" if code == 32 else chr(code)
        if label != want:
            raise SystemExit(f"{path}: expected glyph {want!r} but found {label!r}")
        if len(rows) != 8:
            raise SystemExit(f"{path}: glyph {label!r} has {len(rows)} rows, needs 8")
        glyphs.append(rows)

    for n, line in enumerate(lines, 1):
        if line.startswith("#") and label is None or not line.strip():
            continue
        if line.startswith(": "):
            flush()
            label, rows = line[2:], []
            continue
        if len(line) != 8 or set(line) - {"#", "."}:
            raise SystemExit(f"{path}:{n}: rows must be 8 characters of '#' and '.'")
        rows.append(int(line.replace("#", "1").replace(".", "0"), 2))
    flush()
    if len(glyphs) != LAST - FIRST + 1:
        raise SystemExit(f"{path}: found {len(glyphs)} glyphs, needs {LAST - FIRST + 1}")
    return glyphs


def c_array(symbol, src):
    glyphs = parse(src)
    # comment labels: spell out the characters that could end a comment or a line
    names = {32: "space", 42: "star", 47: "slash", 92: "backslash"}
    lines = []
    for i, g in enumerate(glyphs):
        code = FIRST + i
        lines.append("    {" + ", ".join(f"0x{b:02X}" for b in g) + "}" + f", /* {code} {names.get(code, chr(code))} */")
    return f"/* {Path(src).name} */\nconst uint8_t {symbol}[{len(glyphs)}][8] = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    if len(sys.argv) < 3 or any("=" not in a for a in sys.argv[2:]):
        raise SystemExit(__doc__)
    out, pairs = sys.argv[1], [a.split("=", 1) for a in sys.argv[2:]]
    text = "/* Generated by tools/font2c.py. Do not edit. */\n#include <stdint.h>\n\n"
    text += "\n".join(c_array(sym, src) for sym, src in pairs)
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text(text)


if __name__ == "__main__":
    main()
